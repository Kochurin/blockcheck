CREATE TABLE IF NOT EXISTS reports (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  ts INTEGER NOT NULL,
  country TEXT,
  region TEXT,
  rc TEXT,
  op TEXT,
  res TEXT NOT NULL,
  wl INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS reports_ts ON reports(ts);
CREATE TABLE IF NOT EXISTS seen (h TEXT PRIMARY KEY, ts INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS ooni (svc TEXT, asn INTEGER, n INTEGER, bad INTEGER);
CREATE TABLE IF NOT EXISTS asn (asn INTEGER PRIMARY KEY, holder TEXT);
CREATE TABLE IF NOT EXISTS meta (k TEXT PRIMARY KEY, v TEXT);
